#!/usr/bin/env node
// The factory's final vector logo, read from brand/logo/*.svg (supplied by management, shapes untouched: only the group order,
// the class and the fill are dropped so that CSS / canvas can colour them).
//   as a module  : import { LOGO, logoSprite, logoSvg } from './logo.mjs'   (used by build.mjs and screenshots.mjs)
//   as a script  : node tools/logo.mjs   regenerates assets/js/engine/logo-paths.js and assets/img/favicon.svg
//
// Each logo file has three groups, in this order: English wordmark ("JORDAN CANNING"), Arabic line, gear mark.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BRAND = path.resolve(ROOT, '..', 'brand', 'logo');

function pathOf(el) {
  if (el[0] === 'path') return el[1].d;
  if (el[0] === 'polygon') { const n = el[1].points.trim().split(/[\s,]+/).map(Number); let d = ''; for (let i = 0; i < n.length; i += 2) d += (i ? 'L' : 'M') + n[i] + ',' + n[i + 1]; return d + 'Z'; }
  if (el[0] === 'rect') { const { x, y, width: w, height: h } = el[1]; return `M${x},${y}h${w}v${h}h-${w}Z`; }
  throw new Error('unsupported logo element ' + el[0]);
}
function attrs(s) { const o = {}; for (const m of s.matchAll(/([\w-]+)="([^"]*)"/g)) o[m[1]] = m[2]; return o; }

function parse(file) {
  const src = fs.readFileSync(path.join(BRAND, file), 'utf8');
  const viewBox = src.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const body = src.slice(src.indexOf('<g id="Layer_1-2"'));
  const groups = body.split(/<g>/).slice(1).map((chunk) => {
    const els = [...chunk.matchAll(/<(path|polygon|rect)\b([^>]*?)\/?>/g)].map((m) => [m[1], attrs(m[2])]);
    return els.length ? els.map(pathOf).join('') : '';
  }).filter(Boolean);
  if (groups.length !== 3) throw new Error(file + ': expected 3 groups (word, arabic, gear), found ' + groups.length);
  return { viewBox, word: groups[0], arabic: groups[1], gear: groups[2] };
}

// Bounding boxes of the three groups (x, y, w, h), measured once with getBBox() in Chromium on the supplied files.
const BOX = {
  'logo-horizontal.svg': { word: [293.1, 72.1, 723.8, 63.1], arabic: [294.2, 146.8, 721.6, 80.3], gear: [0, 0, 274, 275.9] },
  'logo-vertical.svg': { word: [0, 319.6, 774.3, 67.5], arabic: [1.2, 399.5, 772, 85.9], gear: [240.6, 0, 293.2, 295.1] }
};
const H = { ...parse('logo-horizontal.svg'), box: BOX['logo-horizontal.svg'] };
const V = { ...parse('logo-vertical.svg'), box: BOX['logo-vertical.svg'] };
export const LOGO = { H, V };

// One hidden <svg> per page: <use href="#lg-gear"> and <use href="#lg-word"> (English + Arabic lines, laid out as in the horizontal logo).
// No fill is set here, so the logo takes the CSS colour (currentColor): Pantone navy in light mode, white in dark mode and on navy sections.
export const logoSprite = () => `<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs><path id="lg-gear" d="${H.gear}"/><path id="lg-word" d="${H.word}${H.arabic}"/></defs></svg>`;
export const logoSvg = (cls = 'logo') => `<svg class="${cls}" viewBox="${H.viewBox.join(' ')}" aria-hidden="true" focusable="false"><use class="logo__gear" href="#lg-gear"/><use href="#lg-word"/></svg>`;
// Standalone, fully self-contained version (used by the OG card and the favicon)
export const logoStandalone = (fill) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${H.viewBox.join(' ')}" fill="${fill}"><path d="${H.gear}"/><path d="${H.word}${H.arabic}"/></svg>`;

const round = (d) => d.replace(/-?(?:\d*\.\d+|\d+)/g, (n) => ' ' + +(+n).toFixed(1) + ' ').replace(/\s+/g, ' ').replace(/ ?([a-zA-Z]) ?/g, '$1').trim(); // 1 decimal is plenty for a canvas texture

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // runtime data for the 3D artwork (Path2D on the canvas): the vertical lock-up (gear above the wordmark) and the gear alone
  const js = `// GENERATED by tools/logo.mjs from brand/logo/logo-vertical.svg: do not edit. Path data of the factory logo, used by art.js (Path2D).
// vertical lock-up: gear mark on top, "JORDAN CANNING" and the Arabic line below. Boxes are [x, y, width, height].
export const LOGO_V = { w: ${V.viewBox[2]}, h: ${V.viewBox[3]}, gear: '${round(V.gear)}', word: '${round(V.word)}', arabic: '${round(V.arabic)}', gearBox: ${JSON.stringify(V.box.gear)}, wordBox: ${JSON.stringify(V.box.word)}, arabicBox: ${JSON.stringify(V.box.arabic)} };
`;
  fs.writeFileSync(path.join(ROOT, 'assets/js/engine/logo-paths.js'), js);
  // favicon: the gear mark only, brand navy on a rounded white tile so it stays legible on dark browser chrome
  const [gx, gy, gw, gh] = H.box.gear, pad = 22, s = Math.max(gw, gh) + pad * 2;
  const fav = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${s} ${s}"><rect width="${s}" height="${s}" rx="${+(s * 0.22).toFixed(1)}" fill="#fff"/><path transform="translate(${+((s - gw) / 2 - gx).toFixed(1)} ${+((s - gh) / 2 - gy).toFixed(1)})" fill="#002F6C" d="${round(H.gear)}"/></svg>\n`;
  fs.writeFileSync(path.join(ROOT, 'assets/img/favicon.svg'), fav);
  console.log('wrote assets/js/engine/logo-paths.js and assets/img/favicon.svg');
}
